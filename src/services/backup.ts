import { db } from '../db';
import {
  CURRENT_BACKUP_VERSION,
  type BackupPayload,
  type BackupValidationResult,
  type RestoreMode,
  type RestoreResult,
  type Product,
  type Sale,
  type StockAdjustment,
  type ShopProfile,
  type Unit,
  type ProductStatus,
  type StockAdjustmentReason,
  type ProductBatch,
} from '../types';
import { getShopProfile, saveShopProfile } from './index';
import { getCustomCategories, saveCustomCategories } from './categories';

const VALID_UNITS: Set<Unit> = new Set([
  'piece',
  'packet',
  'bottle',
  'kg',
  'g',
  'litre',
  'ml',
  'dozen',
]);

const VALID_STATUSES: Set<ProductStatus> = new Set(['active', 'archived']);

const VALID_REASONS: Set<StockAdjustmentReason> = new Set([
  'manual_correction',
  'restock',
  'damage',
  'return',
  'reversal',
  'expired',
]);

/**
 * Generate a complete, versioned snapshot of the store's data from IndexedDB & LocalStorage.
 */
export async function generateBackupPayload(): Promise<BackupPayload> {
  const [products, sales, stockAdjustments, profile, batches] = await Promise.all([
    db.products.toArray(),
    db.sales.toArray(),
    db.stockAdjustments.toArray(),
    getShopProfile(),
    db.batches.toArray(),
  ]);

  const customCategories = getCustomCategories();
  const exportedAt = Date.now();

  return {
    metadata: {
      app: 'SaudaSamrat',
      version: CURRENT_BACKUP_VERSION,
      exportedAt,
      appName: profile?.shopName || 'SaudaSamrat Kirana Store',
      recordCounts: {
        products: products.length,
        sales: sales.length,
        stockAdjustments: stockAdjustments.length,
        hasProfile: !!profile,
        customCategories: customCategories.length,
        batches: batches.length,
      },
    },
    data: {
      products,
      sales,
      stockAdjustments,
      profile,
      customCategories,
      batches,
    },
  };
}

/**
 * Exports data to a downloadable JSON file in the browser without network access.
 */
export async function exportBackupFile(): Promise<{
  filename: string;
  payload: BackupPayload;
}> {
  const payload = await generateBackupPayload();
  const json = JSON.stringify(payload, null, 2);

  const dateStr = new Date(payload.metadata.exportedAt)
    .toISOString()
    .slice(0, 10);
  const filename = `saudasamrat-backup-${dateStr}.json`;

  if (typeof window !== 'undefined' && typeof document !== 'undefined') {
    const blob = new Blob([json], { type: 'application/json;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  }

  return { filename, payload };
}

/**
 * Validates untrusted imported JSON content against schema constraints and prevents prototype pollution.
 */
export function validateBackupContent(rawInput: unknown): BackupValidationResult {
  if (typeof rawInput === 'string') {
    const trimmed = rawInput.trim();
    if (!trimmed) {
      return {
        valid: false,
        error: 'Backup file is empty',
        errorCode: 'EMPTY_FILE',
      };
    }
    try {
      rawInput = JSON.parse(trimmed);
    } catch {
      return {
        valid: false,
        error: 'File is not a valid JSON document',
        errorCode: 'INVALID_JSON',
      };
    }
  }

  if (!rawInput || typeof rawInput !== 'object' || Array.isArray(rawInput)) {
    return {
      valid: false,
      error: 'Backup payload must be a JSON object',
      errorCode: 'MALFORMED_STRUCTURE',
    };
  }

  const raw = rawInput as Record<string, unknown>;

  // Check top-level metadata
  if (!raw.metadata || typeof raw.metadata !== 'object') {
    return {
      valid: false,
      error: 'Missing backup metadata header',
      errorCode: 'MALFORMED_STRUCTURE',
    };
  }

  const meta = raw.metadata as Record<string, unknown>;
  if (meta.app !== 'SaudaSamrat') {
    return {
      valid: false,
      error: 'File was not generated by SaudaSamrat',
      errorCode: 'UNSUPPORTED_APP',
    };
  }

  if (typeof meta.version !== 'string' || !meta.version.startsWith('1.')) {
    return {
      valid: false,
      error: `Unsupported backup version: ${String(meta.version)}`,
      errorCode: 'UNSUPPORTED_VERSION',
    };
  }

  if (!raw.data || typeof raw.data !== 'object') {
    return {
      valid: false,
      error: 'Backup data section is missing',
      errorCode: 'MALFORMED_STRUCTURE',
    };
  }

  const data = raw.data as Record<string, unknown>;

  if (!Array.isArray(data.products)) {
    return {
      valid: false,
      error: 'Products must be an array',
      errorCode: 'MALFORMED_STRUCTURE',
    };
  }

  if (!Array.isArray(data.sales)) {
    return {
      valid: false,
      error: 'Sales must be an array',
      errorCode: 'MALFORMED_STRUCTURE',
    };
  }

  if (!Array.isArray(data.stockAdjustments)) {
    return {
      valid: false,
      error: 'Stock adjustments must be an array',
      errorCode: 'MALFORMED_STRUCTURE',
    };
  }

  const sanitizedProducts: Product[] = [];
  const productIds = new Set<string>();

  for (let i = 0; i < data.products.length; i++) {
    const item = data.products[i];
    if (!item || typeof item !== 'object') {
      return {
        valid: false,
        error: `Product at index ${i} is not a valid object`,
        errorCode: 'INVALID_RECORD',
      };
    }

    const p = item as Record<string, unknown>;
    const id = typeof p.id === 'string' ? p.id.trim() : '';
    const name = typeof p.name === 'string' ? p.name.trim() : '';
    const category = typeof p.category === 'string' ? p.category.trim() : '';
    const quantity = typeof p.quantity === 'number' ? p.quantity : Number(p.quantity);
    const unit = p.unit as Unit;
    const threshold =
      typeof p.lowStockThreshold === 'number'
        ? p.lowStockThreshold
        : Number(p.lowStockThreshold);
    const status = (p.status as ProductStatus) || 'active';
    const createdAt = typeof p.createdAt === 'number' ? p.createdAt : Date.now();
    const updatedAt = typeof p.updatedAt === 'number' ? p.updatedAt : Date.now();

    if (!id) {
      return {
        valid: false,
        error: `Product at index ${i} has no valid ID`,
        errorCode: 'INVALID_RECORD',
      };
    }
    if (productIds.has(id)) {
      return {
        valid: false,
        error: `Duplicate product ID found in backup: ${id}`,
        errorCode: 'DUPLICATE_ID',
      };
    }
    productIds.add(id);

    if (!name) {
      return {
        valid: false,
        error: `Product ${id} has an empty name`,
        errorCode: 'INVALID_RECORD',
      };
    }

    if (!Number.isFinite(quantity) || quantity < 0) {
      return {
        valid: false,
        error: `Product "${name}" has invalid quantity: ${p.quantity}`,
        errorCode: 'INVALID_RECORD',
      };
    }

    if (!VALID_UNITS.has(unit)) {
      return {
        valid: false,
        error: `Product "${name}" has unsupported unit: ${String(p.unit)}`,
        errorCode: 'INVALID_RECORD',
      };
    }

    if (!Number.isFinite(threshold) || threshold < 0) {
      return {
        valid: false,
        error: `Product "${name}" has invalid low-stock threshold: ${p.lowStockThreshold}`,
        errorCode: 'INVALID_RECORD',
      };
    }

    if (!VALID_STATUSES.has(status)) {
      return {
        valid: false,
        error: `Product "${name}" has invalid status: ${String(p.status)}`,
        errorCode: 'INVALID_RECORD',
      };
    }

    sanitizedProducts.push({
      id,
      name,
      category,
      quantity: +quantity.toFixed(6),
      unit,
      lowStockThreshold: +threshold.toFixed(6),
      status,
      ...(typeof p.barcode === 'string' && p.barcode.trim() ? { barcode: p.barcode.trim() } : {}),
      createdAt,
      updatedAt,
    });
  }

  // Validate Sales
  const sanitizedSales: Sale[] = [];
  const saleIds = new Set<string>();

  for (let i = 0; i < data.sales.length; i++) {
    const item = data.sales[i];
    if (!item || typeof item !== 'object') {
      return {
        valid: false,
        error: `Sale at index ${i} is not a valid object`,
        errorCode: 'INVALID_RECORD',
      };
    }

    const s = item as Record<string, unknown>;
    const id = typeof s.id === 'string' ? s.id.trim() : '';
    const productId = typeof s.productId === 'string' ? s.productId.trim() : '';
    const productName = typeof s.productName === 'string' ? s.productName.trim() : '';
    const quantity = typeof s.quantity === 'number' ? s.quantity : Number(s.quantity);
    const unit = s.unit as Unit;
    const soldAt = typeof s.soldAt === 'number' ? s.soldAt : Date.now();

    if (!id) {
      return {
        valid: false,
        error: `Sale at index ${i} is missing an ID`,
        errorCode: 'INVALID_RECORD',
      };
    }
    if (saleIds.has(id)) {
      return {
        valid: false,
        error: `Duplicate sale ID found in backup: ${id}`,
        errorCode: 'DUPLICATE_ID',
      };
    }
    saleIds.add(id);

    if (!productId) {
      return {
        valid: false,
        error: `Sale ${id} is missing a productId`,
        errorCode: 'INVALID_RECORD',
      };
    }

    if (!Number.isFinite(quantity) || quantity <= 0) {
      return {
        valid: false,
        error: `Sale ${id} has non-positive quantity: ${s.quantity}`,
        errorCode: 'INVALID_RECORD',
      };
    }

    if (!VALID_UNITS.has(unit)) {
      return {
        valid: false,
        error: `Sale ${id} has unsupported unit: ${String(s.unit)}`,
        errorCode: 'INVALID_RECORD',
      };
    }

    sanitizedSales.push({
      id,
      productId,
      productName: productName || 'Unknown Item',
      quantity: +quantity.toFixed(6),
      unit,
      soldAt,
    });
  }

  // Validate Stock Adjustments
  const sanitizedAdjustments: StockAdjustment[] = [];
  const adjustmentIds = new Set<string>();

  for (let i = 0; i < data.stockAdjustments.length; i++) {
    const item = data.stockAdjustments[i];
    if (!item || typeof item !== 'object') {
      return {
        valid: false,
        error: `Stock adjustment at index ${i} is not a valid object`,
        errorCode: 'INVALID_RECORD',
      };
    }

    const a = item as Record<string, unknown>;
    const id = typeof a.id === 'string' ? a.id.trim() : '';
    const productId = typeof a.productId === 'string' ? a.productId.trim() : '';
    const delta = typeof a.delta === 'number' ? a.delta : Number(a.delta);
    const reason = a.reason as StockAdjustmentReason;
    const note = typeof a.note === 'string' ? a.note.trim() : undefined;
    const adjustedAt = typeof a.adjustedAt === 'number' ? a.adjustedAt : Date.now();

    if (!id) {
      return {
        valid: false,
        error: `Stock adjustment at index ${i} is missing an ID`,
        errorCode: 'INVALID_RECORD',
      };
    }
    if (adjustmentIds.has(id)) {
      return {
        valid: false,
        error: `Duplicate stock adjustment ID in backup: ${id}`,
        errorCode: 'DUPLICATE_ID',
      };
    }
    adjustmentIds.add(id);

    if (!productId) {
      return {
        valid: false,
        error: `Stock adjustment ${id} is missing a productId`,
        errorCode: 'INVALID_RECORD',
      };
    }

    if (!Number.isFinite(delta) || delta === 0) {
      return {
        valid: false,
        error: `Stock adjustment ${id} has invalid delta: ${a.delta}`,
        errorCode: 'INVALID_RECORD',
      };
    }

    if (!VALID_REASONS.has(reason)) {
      return {
        valid: false,
        error: `Stock adjustment ${id} has invalid reason: ${String(a.reason)}`,
        errorCode: 'INVALID_RECORD',
      };
    }

    sanitizedAdjustments.push({
      id,
      productId,
      delta: +delta.toFixed(6),
      reason,
      note,
      adjustedAt,
      ...(typeof a.reversedAdjustmentId === 'string' && {
        reversedAdjustmentId: a.reversedAdjustmentId.trim(),
      }),
      ...(typeof a.reversedSaleId === 'string' && {
        reversedSaleId: a.reversedSaleId.trim(),
      }),
      ...(typeof a.isReversal === 'boolean' && { isReversal: a.isReversal }),
    });
  }

  // Validate profile (optional)
  let sanitizedProfile: ShopProfile | null = null;
  if (data.profile && typeof data.profile === 'object') {
    const prof = data.profile as Record<string, unknown>;
    const ownerName = typeof prof.ownerName === 'string' ? prof.ownerName.trim() : '';
    const shopName = typeof prof.shopName === 'string' ? prof.shopName.trim() : '';
    const updatedAt = typeof prof.updatedAt === 'number' ? prof.updatedAt : Date.now();

    if (ownerName.length > 50 || shopName.length > 60) {
      return {
        valid: false,
        error: 'Profile names exceed maximum allowable length',
        errorCode: 'INVALID_RECORD',
      };
    }

    if (ownerName || shopName) {
      sanitizedProfile = {
        id: 'profile',
        ownerName,
        shopName,
        updatedAt,
      };
    }
  }

  // Validate custom categories
  const sanitizedCategories: string[] = [];
  if (Array.isArray(data.customCategories)) {
    for (const cat of data.customCategories) {
      if (typeof cat === 'string' && cat.trim()) {
        const trimmed = cat.trim();
        if (trimmed.length <= 40 && !sanitizedCategories.includes(trimmed)) {
          sanitizedCategories.push(trimmed);
        }
      }
    }
  }

  // Validate batches if present
  const sanitizedBatches: ProductBatch[] = [];
  if (Array.isArray(data.batches)) {
    for (const b of data.batches) {
      if (
        b &&
        typeof b.id === 'string' &&
        typeof b.productId === 'string' &&
        typeof b.batchNumber === 'string' &&
        typeof b.expiryDate === 'string' &&
        typeof b.quantity === 'number'
      ) {
        sanitizedBatches.push({
          id: b.id,
          productId: b.productId,
          batchNumber: b.batchNumber.trim(),
          expiryDate: b.expiryDate.trim(),
          quantity: b.quantity,
          receivedAt: typeof b.receivedAt === 'number' ? b.receivedAt : Date.now(),
          ...(b.note && { note: String(b.note).trim() }),
        });
      }
    }
  }

  const sanitizedPayload: BackupPayload = {
    metadata: {
      app: 'SaudaSamrat',
      version: typeof meta.version === 'string' ? meta.version : CURRENT_BACKUP_VERSION,
      exportedAt: typeof meta.exportedAt === 'number' ? meta.exportedAt : Date.now(),
      appName: sanitizedProfile?.shopName || String(meta.appName || 'SaudaSamrat Store'),
      recordCounts: {
        products: sanitizedProducts.length,
        sales: sanitizedSales.length,
        stockAdjustments: sanitizedAdjustments.length,
        hasProfile: !!sanitizedProfile,
        customCategories: sanitizedCategories.length,
        batches: sanitizedBatches.length,
      },
    },
    data: {
      products: sanitizedProducts,
      sales: sanitizedSales,
      stockAdjustments: sanitizedAdjustments,
      profile: sanitizedProfile,
      customCategories: sanitizedCategories,
      batches: sanitizedBatches,
    },
  };

  return {
    valid: true,
    payload: sanitizedPayload,
  };
}

/**
 * Restores store records from a validated BackupPayload using an atomic Dexie transaction.
 * Supports:
 * - 'replace': Clears all current database tables and inserts backup records.
 * - 'merge': Upserts backup records into database tables without deleting existing records.
 */
export async function restoreShopData(
  payload: BackupPayload,
  mode: RestoreMode,
): Promise<RestoreResult> {
  const start = Date.now();

  await db.transaction('rw', db.products, db.sales, db.stockAdjustments, db.profile, db.batches, async () => {
    if (mode === 'replace') {
      // Clear existing records atomically
      await Promise.all([
        db.products.clear(),
        db.sales.clear(),
        db.stockAdjustments.clear(),
        db.profile.clear(),
        db.batches.clear(),
      ]);

      // Bulk add verified records
      if (payload.data.products.length > 0) {
        await db.products.bulkAdd(payload.data.products);
      }
      if (payload.data.sales.length > 0) {
        await db.sales.bulkAdd(payload.data.sales);
      }
      if (payload.data.stockAdjustments.length > 0) {
        await db.stockAdjustments.bulkAdd(payload.data.stockAdjustments);
      }
      if (payload.data.profile) {
        await db.profile.put(payload.data.profile);
      }
      if (payload.data.batches && payload.data.batches.length > 0) {
        await db.batches.bulkAdd(payload.data.batches);
      }
    } else {
      // Merge mode: upsert without deleting
      if (payload.data.products.length > 0) {
        await db.products.bulkPut(payload.data.products);
      }
      if (payload.data.sales.length > 0) {
        await db.sales.bulkPut(payload.data.sales);
      }
      if (payload.data.stockAdjustments.length > 0) {
        await db.stockAdjustments.bulkPut(payload.data.stockAdjustments);
      }
      if (payload.data.batches && payload.data.batches.length > 0) {
        await db.batches.bulkPut(payload.data.batches);
      }
      if (payload.data.profile) {
        const existingProfile = await db.profile.get('profile');
        if (!existingProfile || payload.data.profile.updatedAt >= existingProfile.updatedAt) {
          await db.profile.put(payload.data.profile);
        }
      }
    }
  });

  // Sync shop profile & localStorage
  if (payload.data.profile) {
    if (mode === 'replace') {
      await saveShopProfile({
        ownerName: payload.data.profile.ownerName,
        shopName: payload.data.profile.shopName,
      });
    } else {
      const current = await getShopProfile();
      if (!current || !current.shopName) {
        await saveShopProfile({
          ownerName: payload.data.profile.ownerName,
          shopName: payload.data.profile.shopName,
        });
      }
    }
  }

  // Sync custom categories
  if (mode === 'replace') {
    saveCustomCategories(payload.data.customCategories);
  } else {
    const existing = getCustomCategories();
    const merged = Array.from(new Set([...existing, ...payload.data.customCategories]));
    saveCustomCategories(merged);
  }

  return {
    success: true,
    mode,
    restoredCounts: {
      products: payload.data.products.length,
      sales: payload.data.sales.length,
      stockAdjustments: payload.data.stockAdjustments.length,
      profileRestored: !!payload.data.profile,
      customCategories: payload.data.customCategories.length,
      batches: payload.data.batches ? payload.data.batches.length : 0,
    },
    durationMs: Date.now() - start,
  };
}
